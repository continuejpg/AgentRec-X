"""Canonical end-to-end demo scenario: one runnable, inspectable trajectory.

What this runs
--------------
Exactly the capabilities this repository has already measured, in one request against the
real HTTP surface:

    user need
      -> candidate retrieval from the trusted history recommender
      -> multi-source retrieval from full-catalogue lexical search, through the candidate
         plane, which grounds every identity and records which source proposed it
      -> reciprocal-rank fusion of the sources consulted in one action
      -> hard-constraint verification against the catalogue
      -> feasible-candidate filtering (a candidate ineligible for a proved violation is
         excluded from what may be presented)
      -> a grounded recommendation, plus the bounded loop's terminal state and trajectory

Nothing here is new behaviour: the endpoint it calls composes the accepted pipeline, the
bounded agent loop, the candidate plane and the constraint kernel.  This module only makes
one such run reproducible and readable.

Honesty notes, stated at the point of use
----------------------------------------
* The **default** artifacts are the small synthetic demo catalogue generated by
  ``experiments.build_demo_catalog``.  Its checkpoint is randomly initialised, so the
  *ranking* is meaningless.  What the scenario demonstrates is the pipeline and its trust
  behaviour - grounding, provenance, constraint verdicts, terminal state - which is exactly
  what a synthetic checkpoint can demonstrate and a benchmark cannot be run on.
* The constraint verdicts below **are** real: they are computed from the catalogue records in
  ``recommendation/demo/artifacts/demo_products.jsonl``.
* This is not a benchmark.  Recommendation quality is measured separately, on the public
  dataset, in the Phase-5 benchmark (``docs/PHASE5_HANDOFF.md``).

Usage::

    # against the small offline demo catalogue (no credentials, no network)
    python -m experiments.demo_scenario

    # against a configured deployment (the real accepted artifacts)
    AGENTRECX_CHECKPOINT_PATH=... AGENTRECX_MAPPINGS_PATH=... python -m experiments.demo_scenario
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

#: The scenario.  Chosen so one request exercises retrieval, several sources, a constraint
#: that really removes a candidate, and a feasible result - the whole chain in one turn.
DEMO_CATALOG = REPO_ROOT / "recommendation" / "demo" / "artifacts" / "demo_products.jsonl"
DEMO_ARTIFACTS_DIR = REPO_ROOT / "runs" / "demo_catalog"

SCENARIO: dict[str, Any] = {
    "message": "Recommend waterproof layers and boots for wet trails",
    "history": ["demo-socks", "demo-trail-runner", "demo-fleece"],
    "k": 4,
    "sources": ["history", "catalog_search"],
    "constraints": [{"kind": "price_max", "value": "100"}],
}

#: Environment variables that must be set for the scenario to run against the small demo
#: catalogue.  ``AGENTRECX_MANIFEST_PATH=none`` is required because the accepted run manifest
#: cross-checks the served checkpoint against the accepted training run, and the demo
#: checkpoint is not part of that run.
DEMO_ENV: dict[str, str] = {
    "AGENTRECX_CHECKPOINT_PATH": str(DEMO_ARTIFACTS_DIR / "checkpoint.pt"),
    "AGENTRECX_MAPPINGS_PATH": str(DEMO_ARTIFACTS_DIR / "mappings.json"),
    "AGENTRECX_CATALOG_METADATA_PATH": str(DEMO_CATALOG),
    "AGENTRECX_MEMORY_DB": str(DEMO_ARTIFACTS_DIR / "preference_memory.sqlite3"),
    "AGENTRECX_VERIFY_CHECKPOINT": "0",
    "AGENTRECX_MANIFEST_PATH": "none",
    "OMP_NUM_THREADS": "1",
}


def ensure_demo_artifacts(*, quiet: bool = False) -> dict[str, Any]:
    """Generate the demo checkpoint/mappings when they are missing.

    Idempotent: an existing artifact set is reused, so a second run costs nothing.  Building is
    cheap (a 15-product catalogue and a 32-hidden-unit one-block model) and needs no network.
    """
    from experiments.build_demo_catalog import build_artifacts

    checkpoint = DEMO_ARTIFACTS_DIR / "checkpoint.pt"
    mappings = DEMO_ARTIFACTS_DIR / "mappings.json"
    if checkpoint.exists() and mappings.exists() and DEMO_CATALOG.exists():
        return {"generated": False, "catalog": str(DEMO_CATALOG)}
    built = build_artifacts(out_dir=DEMO_ARTIFACTS_DIR, catalog_path=DEMO_CATALOG)
    if not quiet:
        print(f"generated demo artifacts in {DEMO_ARTIFACTS_DIR}")
    return {"generated": True, **built}


def run_scenario(*, client: Any = None, payload: dict[str, Any] | None = None) -> dict[str, Any]:
    """Run the scenario through the real HTTP surface and return the parsed response.

    ``client`` may be injected (the tests do) so the scenario can be exercised without
    composing a server; otherwise it is built the same way the served process builds it.
    """
    body = dict(payload or SCENARIO)
    if client is not None:
        response = client.post("/v1/demo/agent/recommend", json=body)
        response.raise_for_status()
        return response.json()

    from fastapi.testclient import TestClient

    from recommendation.api.app import create_app

    # Self-sufficient: an unconfigured deployment with no demo artifacts would otherwise fail
    # to start here, and this function is what the CI smoke and the docs rely on.
    if not _deployment_is_configured():
        ensure_demo_artifacts(quiet=True)
        os.environ.update(DEMO_ENV)

    with TestClient(create_app(enable_demo=True)) as built:
        response = built.post("/v1/demo/agent/recommend", json=body)
        response.raise_for_status()
        return response.json()


def _deployment_is_configured() -> bool:
    """True when the environment already names a checkpoint and mappings artifact.

    Read from the same variables the service reads, so "configured" here means exactly what it
    means at startup; anything else is the built-in demo catalogue's job.
    """
    return bool(
        os.environ.get("AGENTRECX_CHECKPOINT_PATH")
        and os.environ.get("AGENTRECX_MAPPINGS_PATH")
    )


def format_trajectory(body: dict[str, Any]) -> str:
    """Render the response as the compact, readable block the documentation shows."""
    lines: list[str] = []
    lines.append(
        f"route={body['route']}  control_plane={body['control_plane']}  "
        f"terminal={body['terminal']['status']}/{body['terminal']['termination_reason']}  "
        f"succeeded={body['terminal']['succeeded']}"
    )
    grounded = body["grounded"]
    lines.append(
        f"grounded={grounded['grounded_count']}  sources={list(grounded['sources_present'])}  "
        f"multi_source={grounded['multi_source_count']}  "
        f"ungrounded={grounded['ungrounded_count']}"
    )
    eligibility = body["eligibility"]
    if eligibility["evaluated"]:
        lines.append(
            "constraints="
            + ", ".join(f"{r['kind']}<={r['expected']}" for r in eligibility["requirements"])
            + f"  verified={eligibility['verified_eligible_count']}"
            f" ineligible={eligibility['ineligible_count']}"
            f" unresolved={eligibility['unresolved_count']}"
        )
        projection = eligibility.get("projection") or {}
        if projection.get("excluded"):
            for item in projection["excluded"]:
                lines.append(f"  excluded {item['parent_asin']}: {item['reason']}")
    else:
        lines.append("constraints=none active (nothing was evaluated)")

    lines.append("recommendations:")
    for item in body["recommendations"]:
        title = item.get("title") or "(no title)"
        sources = ",".join(item.get("sources") or []) or "-"
        kind = item.get("score_kind") or "-"
        lines.append(
            f"  {item['rank']}. {item['parent_asin']:<22} {title:<32} "
            f"score={item['score']:.4f} ({kind}) sources={sources}"
        )
    if not body["recommendations"]:
        lines.append("  (none - the run presented no verified candidate)")

    lines.append("trajectory:")
    for step in body["trajectory"]["steps"]:
        lines.append(
            f"  step {step['step']}: action={step['action']} executed={step['validated']} "
            f"observation={step['observation_type']} candidates={step['candidate_count']} "
            f"eligibility={step['eligibility_state']} refusals={list(step['refusal_codes'])}"
        )
    timing = body["timing"]
    lines.append(
        f"timing: total={timing['total_ms']:.1f} ms agent={timing['agent_ms']:.1f} ms "
        f"serialize={timing['serialize_ms']:.1f} ms"
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run the canonical AgentRec-X demo scenario")
    parser.add_argument(
        "--json", action="store_true", help="print the raw response instead of the summary"
    )
    parser.add_argument(
        "--configured",
        action="store_true",
        help=(
            "use an already-configured deployment instead of the built-in demo catalogue "
            "(no AGENTRECX_* overrides are applied)"
        ),
    )
    args = parser.parse_args(argv)

    if not args.configured:
        built = ensure_demo_artifacts(quiet=args.json)
        if built.get("generated") and not args.json:
            print("(synthetic, untrained demo checkpoint - the ranking carries no quality claim)\n")
        os.environ.update(DEMO_ENV)

    body = run_scenario()
    if args.json:
        print(json.dumps(body, indent=2, sort_keys=True))
    else:
        print("AgentRec-X demo scenario")
        print("=" * 78)
        print(json.dumps({k: v for k, v in SCENARIO.items()}, indent=2))
        print("-" * 78)
        print(format_trajectory(body))
    return 0


if __name__ == "__main__":  # pragma: no cover - manual invocation
    raise SystemExit(main())
