"""Unified decision state and event-sourced belief management (M5-MVP).

The central state abstraction of the AgentRec-X 3.0 direction.  Memory is not the
centre of the agent: it is a projection of validated user information, and every change
arrives as a versioned event reduced deterministically into a typed state.

```text
user interaction -> StateEvent -> append-only SQLite event store
                -> BeliefUpdater -> UnifiedDecisionState
                -> StateProjector: for_agent / for_ranker / for_constraints
```

The engineering slice is intentionally model-free: importing this package requires only
Pydantic and the standard library.  It does not train a model, run an Agent policy, call
an LLM, or change the default Serving V1 path or the accepted M9 preference memory.
Full contract: ``docs/M5_UNIFIED_DECISION_STATE.md``.
"""

